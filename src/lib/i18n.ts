export type TranslationKey = keyof typeof messages.en;

export function resolveUiLanguage(language?: string | null): UiLanguage {
  if (language?.trim().toLowerCase().startsWith("pt")) {
    return "pt-BR";
  }

  return "en";
}

export function translate(language: string | null | undefined, key: TranslationKey, values?: Record<string, string | number>) {
  const locale = resolveUiLanguage(language);
  const template = messages[locale][key] ?? messages.en[key];

  if (!values) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (_, token: string) => String(values[token] ?? `{${token}}`));
}
